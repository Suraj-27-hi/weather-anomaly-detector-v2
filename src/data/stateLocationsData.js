// Flattened list of all locations for instant autocomplete across India
export const ALL_INDIAN_LOCATIONS = Object.entries(STATE_LOCATIONS_MAP).flatMap(([state, locs]) =>
  locs.map(l => ({ ...l, state }))
);

// Search function that searches local catalog instantly and ranks matches
export function searchLocalLocations(query, selectedState = "") {
  if (!query || query.trim().length === 0) return [];
  const q = query.trim().toLowerCase();

  return ALL_INDIAN_LOCATIONS.filter(item => {
    // Check if name or state matches
    const nameMatch = item.name.toLowerCase().includes(q);
    const stateMatch = item.state.toLowerCase().includes(q);
    const keywordMatch = item.keywords && item.keywords.some(k => k.toLowerCase().includes(q));

    return nameMatch || stateMatch || keywordMatch;
  }).sort((a, b) => {
    // Boost matches in the currently selected state
    const aInState = selectedState && a.state.toLowerCase() === selectedState.toLowerCase() ? 1 : 0;
    const bInState = selectedState && b.state.toLowerCase() === selectedState.toLowerCase() ? 1 : 0;
    if (aInState !== bInState) return bInState - aInState;

    // Boost exact startsWith name match
    const aStarts = a.name.toLowerCase().startsWith(q) ? 1 : 0;
    const bStarts = b.name.toLowerCase().startsWith(q) ? 1 : 0;
    if (aStarts !== bStarts) return bStarts - aStarts;

    return a.name.localeCompare(b.name);
  }).slice(0, 10);
}
